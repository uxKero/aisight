export const DICTS: Record<Lang, Dict> = { en, es, zh }

export type Key = keyof Dict

export const DEFAULT_TEMPLATES: Record<Lang, string[]> = {
  en: ['Fix what I marked', "What's wrong here?", 'Make it look exactly like this', 'This error shows up when I do this:'],
  es: ['Arregla lo que marqué', '¿Qué está mal acá?', 'Haz que se vea igual a esto', 'Este error aparece al hacer esto:'],
  zh: ['修复我标记的地方', '这里有什么问题？', '让它看起来和这个一模一样', '我这样操作时出现了这个错误：'],
}

export const LOCALES: Record<Lang, string> = { en: 'en', es: 'es', zh: 'zh-CN' }

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang]?.[key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export function translateError(lang: Lang, raw: string): string {
  const key = `err.${raw.trim()}` as Key
  return key in en ? translate(lang, key) : raw
}

export const LangContext = createContext<Lang>('en')

export function useT() {
  const lang = useContext(LangContext)
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

export function useLang() {
  return useContext(LangContext)
}
